# %% [markdown]
# # Removal of Co, Li and PW metals by dolomite: a kinetic batch reaction model
#
# **Following Omar & Vilcáez (2024)**, *The role of alkalinity on metals removal from petroleum
# produced water by dolomite*, Applied Geochemistry 161, 105879 — the same group, the same
# apparatus, the same modelling strategy.
#
# ## Why this replaces the equilibrium-inversion approach
#
# The earlier analysis treated each sampling as an independent equilibrium point and inverted the
# mass action law at it. That is Belova's procedure for a true adsorption edge, and it fails here
# because these are **kinetic batch experiments**: pH, alkalinity and the Ca/Mg competitor load
# are *generated by dolomite dissolution during the run*, not imposed.
#
# Omar & Vilcáez model exactly this system and do it differently:
#
# | Step | Treatment |
# |---|---|
# | Dolomite dissolution | **kinetic**, transition state theory (Lasaga, 1984), their Eq. 2 |
# | Aqueous complexation | equilibrium, their Table 5 |
# | Carbonate mineral precipitation | equilibrium (instantaneous), their Table 6 |
# | Sorption | three dolomite hydration sites, K_int as their Eq. 1 |
# | Output | **concentration against time**, their Fig. 14 |
# | Mechanism split | run with precipitation only, then with sorption + precipitation |
#
# Crucially, on how they obtain the constants: *"K_int for Ca and Mg corresponds to measured
# values at low salinity (Pokrovsky et al., 1999), whereas **K_int for Sr, Cd, and Pb are assumed
# values based on observed removal levels**."* The constant is **calibrated so that the simulated
# concentration profile reproduces the measured one** — not inverted point by point. That is the
# procedure applied here to Co and Li.
#
# Their published values, which set the scale:
#
# | Metal | log K_int | removal in their PW |
# |---|---|---|
# | Cd | −0.233 | high |
# | Ca | −1.8 (Pokrovsky) | — |
# | Mg | −2.0 (Pokrovsky) | — |
# | Pb | −2.33 | high, mostly precipitation |
# | Sr | −4.66 | low |

