# %% [markdown]
# ## 3 — The model
#
# One well-mixed batch, integrated forward in time. At each step:
#
# 1. **Dolomite dissolves kinetically**, transition state theory (Lasaga, 1984; Omar & Vilcáez
#    Eq. 2), releasing Ca²⁺, Mg²⁺ and 2 HCO₃⁻ per mole and consuming 2 H⁺:
#
#    $$-R_{\mathrm{dol}} = A\,k_m\,[\mathrm{H^+}]\left\{1 -
#    \frac{[\mathrm{HCO_3^-}]^2[\mathrm{Ca^{2+}}][\mathrm{Mg^{2+}}]}{[\mathrm{H^+}]^2 K_{eq}}\right\}$$
#
# 2. **The solution re-equilibrates**: pH from charge balance, aqueous complexes from Table 5.
# 3. **Any supersaturated carbonate precipitates** to its solubility (instantaneous, Table 6).
# 4. **Sorption re-equilibrates** on the carbonate site, competitively across all cations.
#
# pH is an **output**, not an input. That is the central difference from the earlier treatment
# and the reason this reproduces a drifting batch rather than fighting it.

# %%
head(3, "The model")

DOL_GL, SSA = 60.0, 0.76                 # g/L and m2/g
S_AREA      = DOL_GL*SSA                 # 45.6 m2 per litre
S_T         = {k: v*S_AREA for k, v in SITE_DENS.items()}     # mol/L of suspension
K_M         = 3.0e-7                     # mol m-2 s-1, TST intrinsic rate constant (EQ3/6 range)

def gamma(I, z):
    """Davies activity coefficient."""
    f = -0.509*(np.sqrt(I)/(1 + np.sqrt(I)) - 0.3*I)
    return 10**(f*z*z)

def speciate(tot, CT, pH_guess=7.0):
    """Given total dissolved concentrations and total carbonate, solve pH from charge balance
    and return free-ion concentrations. tot carries Na, Cl and every divalent metal."""
    I = 0.5*(tot["Na"] + tot["Cl"] + sum(4*v for k, v in tot.items() if k not in ("Na", "Cl")))
    g1, g2 = gamma(I, 1), gamma(I, 2)

    def charge(pH):
        h = 10**(-pH)/g1
        oh = 10**(LOGK_H2O)/(10**(-pH))/g1
        # carbonate distribution over CT
        a_h = 10**(-pH)
        f_hco3 = 1.0
        f_co3  = 1.0/(10**LOGK_CO3*a_h)
        f_co2  = a_h/10**LOGK_CO2
        den = f_co2 + f_hco3 + f_co3
        hco3, co3 = CT*f_hco3/den, CT*f_co3/den
        pos = tot["Na"] + h
        for m, t in tot.items():
            if m in ("Na", "Cl"): continue
            z = 1 if m == "Li" else 2
            pos += z*t
        neg = tot["Cl"] + hco3 + 2*co3 + oh
        return pos - neg

    try:
        pH = brentq(charge, 1.0, 13.0, xtol=1e-8)
    except ValueError:
        pH = pH_guess
    a_h = 10**(-pH)
    f_hco3, f_co3, f_co2 = 1.0, 1.0/(10**LOGK_CO3*a_h), a_h/10**LOGK_CO2
    den = f_co2 + f_hco3 + f_co3
    return dict(pH=pH, I=I, g1=g1, g2=g2, a_h=a_h,
                HCO3=CT*f_hco3/den, CO3=CT*f_co3/den, CO2=CT*f_co2/den)

def free_fraction(metal, sp, tot):
    """Fraction of the dissolved metal present as the free ion, from the Table 5 complexes."""
    if metal == "Li": return 0.9
    d = 1.0
    d += tot["Cl"]/10**LOGK_MECL.get(metal, 0.0)                    # MeCl+
    d += sp["HCO3"]/10**LOGK_MECO3.get(metal, 7.0)/sp["a_h"]        # MeCO3(aq)
    d += 1.0/(10**LOGK_MEOH.get(metal, 12.0)*sp["a_h"])             # MeOH+
    return 1.0/d

def mineral_SI(metal, mineral, me_free, sp):
    """SI for MeCO3 + H+ = Me2+ + HCO3-, so IAP/K = (Me)(HCO3)/((H)(K))."""
    iap = me_free*sp["g2"]*sp["HCO3"]*sp["g1"]/(sp["a_h"])
    return np.log10(iap) - LOGK_MIN[mineral]

def sorb(sp, free, logK):
    """Competitive sorption on the carbonate site, Omar & Vilcaez Eq. 1.

    K_int = [>CO3Me+][H+] / ([>CO3H0][Me2+])  =>  [>CO3Me+] = K [>CO3H0] (Me) / (H)
    with the site balance  [>CO3]_T = [>CO3H0] + [>CO3-] + sum([>CO3Me+]).
    Returns moles sorbed per litre for each metal.
    """
    d = 1.0 + 10**LOGK_CO3H/sp["a_h"]                      # >CO3H0 and >CO3-
    for m, a in free.items():
        if logK.get(m) is None: continue
        d += 10**logK[m]*a*sp["g2"]/sp["a_h"]
    CO3H0 = S_T["CO3"]/d
    return {m: 10**logK[m]*free[m]*sp["g2"]/sp["a_h"]*CO3H0
            for m in free if logK.get(m) is not None}

def simulate(tot0, CT0, metals, logK, days=6.0, nstep=1440, sorption=True,
             precipitation=True, k_m=K_M):
    """Integrate the batch. Returns a DataFrame of concentration against time."""
    tot = dict(tot0); CT = CT0
    ppt = {m: 0.0 for m in metals}                 # moles per litre precipitated
    dt  = days*86400.0/nstep
    out = []
    for step in range(nstep + 1):
        sp   = speciate(tot, CT)
        free = {m: tot[m]*free_fraction(m, sp, tot) for m in metals}

        # --- record
        srb = sorb(sp, free, logK) if sorption else {m: 0.0 for m in metals}
        row = dict(t_day=step*dt/86400.0, pH=sp["pH"], CT=CT,
                   Ca=tot["Ca"], Mg=tot["Mg"], alk=sp["HCO3"] + 2*sp["CO3"])
        for m in metals:
            row[m] = max(tot[m] - srb.get(m, 0.0), 0.0)     # dissolved, after sorption
            row[m + "_sorbed"] = srb.get(m, 0.0)
            row[m + "_ppt"]    = ppt[m]
        out.append(row)
        if step == nstep: break

        # --- 1. kinetic dolomite dissolution (Lasaga 1984; Omar & Vilcaez Eq. 2)
        Q = (sp["HCO3"]*sp["g1"])**2*(tot["Ca"]*sp["g2"])*(tot["Mg"]*sp["g2"])/(sp["a_h"]**2)
        omega = Q/10**LOGK_MIN["Dolomite"]
        rate = S_AREA*k_m*sp["a_h"]*(1.0 - omega)           # mol L-1 s-1, may be negative
        dmol = rate*dt
        tot["Ca"] += dmol; tot["Mg"] += dmol; CT += 2*dmol

        # --- 2. equilibrium precipitation of any supersaturated carbonate
        if precipitation:
            sp = speciate(tot, CT)
            for mineral, m in MIN_CATION.items():
                if m not in tot or tot[m] <= 0: continue
                fr = free_fraction(m, sp, tot)
                si = mineral_SI(m, mineral, tot[m]*fr, sp)
                if si > 0:
                    # remove metal and carbonate until SI returns to zero
                    lo, hi = 0.0, min(tot[m], CT)*0.999
                    for _ in range(40):
                        mid = 0.5*(lo + hi)
                        t2 = dict(tot); t2[m] -= mid
                        s2 = speciate(t2, CT - mid)
                        if mineral_SI(m, mineral, t2[m]*free_fraction(m, s2, t2), s2) > 0:
                            lo = mid
                        else:
                            hi = mid
                    tot[m] -= hi; CT -= hi
                    if m in ppt: ppt[m] += hi
    return pd.DataFrame(out)

print("Model assembled:")
print("  kinetic dolomite dissolution -> equilibrium speciation -> equilibrium carbonate")
print("  precipitation -> competitive sorption on the carbonate site.")
print(f"  Surface area {S_AREA:.1f} m2/L, carbonate sites {S_T['CO3']*1e3:.3f} mmol/L, k_m = {K_M:.1e} mol m-2 s-1.")
print("  pH is an OUTPUT of the dissolution, not an input.")

# %% [markdown]
# ## 4 — Calibration against the produced-water experiment
#
# Omar & Vilcáez assign K_int for Sr, Cd and Pb as *"assumed values based on observed removal
# levels"*. The same procedure is applied here: for each metal, log K_int is adjusted until the
# simulated day-6 dissolved concentration matches the measured one. Ca and Mg keep Pokrovsky's
# measured values, and Sr, Cd and Pb keep the published Omar & Vilcáez values, so the only
# quantities determined here are those for **Co, Li and Ba**.

# %%
head(4, "Calibration against the produced-water experiment")

NACL = 40.0/58.44
def pw_initial():
    """Initial totals for the produced water, mol/L, from the day-0 row."""
    r = PW[(PW.batch == "pH6") & (PW.day == 0)].iloc[0]
    tot = {"Na": NACL, "Cl": NACL}
    tot["Ca"] = r.Ca_ppm/MM["Ca"]/1e3
    tot["Mg"] = r.Mg_ppm/MM["Mg"]/1e3
    for m in PW_METALS:
        tot[m] = r[m]/MM[m]/1e3
    # chloride balances the added salts
    tot["Cl"] = NACL + 2*(tot["Ca"] + tot["Mg"]) + sum(
        (1 if m == "Li" else 2)*tot[m] for m in PW_METALS)
    return tot

TOT0 = pw_initial()
CT0  = 1.0e-3            # mol/L initial dissolved inorganic carbon, from the day-0 pH of 6.32
MET  = ["Ca", "Mg"] + PW_METALS

def day6_measured(metal):
    return PW[(PW.batch == "pH6") & (PW.day == 6)][metal].iloc[0]

def predict_day6(metal, logK_metal, base=None):
    """Simulate with one metal's constant set to logK_metal; return day-6 dissolved mg/L."""
    lk = dict(LOGK_INT) if base is None else dict(base)
    lk[metal] = logK_metal
    df = simulate(TOT0, CT0, MET, lk, days=6.0, nstep=360)
    return df[metal].iloc[-1]*MM[metal]*1e3

def calibrate(metal, base, lo=-7.0, hi=2.0):
    """Adjust log K_int until the simulated day-6 concentration matches the measured one."""
    target = day6_measured(metal)
    f = lambda k: (predict_day6(metal, k, base) - target)**2
    res = minimize_scalar(f, bounds=(lo, hi), method="bounded",
                          options={"xatol": 0.02})
    return float(res.x), predict_day6(metal, float(res.x), base), target

base = dict(LOGK_INT)
rows = []
for metal in ["Co", "Li", "Ba"]:
    k, pred, meas = calibrate(metal, base)
    base[metal] = k
    c0 = PW[(PW.batch == "pH6") & (PW.day == 0)][metal].iloc[0]
    rows.append(dict(metal=metal, logK_int=k, predicted_day6_mgL=pred,
                     measured_day6_mgL=meas,
                     removal_pred=100*(1 - pred/c0), removal_meas=100*(1 - meas/c0)))
cal = pd.DataFrame(rows)
show(cal)
LOGK_ALL = dict(base)
print("\nFull constant set now in use (Omar & Vilcaez values kept, this study's added):")
show(pd.DataFrame([(m, v, "Pokrovsky 1999" if m in ("Ca","Mg") else
                    "Omar & Vilcaez 2024" if m in ("Sr","Cd","Pb") else "this study")
                   for m, v in LOGK_ALL.items()],
                  columns=["metal", "log K_int", "source"]))
